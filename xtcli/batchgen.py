"""BatchProcessor script generation.

Command grammar implemented by TESVT_main.pas `batchCommands`/`runCommands`:
rule blocks between StartRule/EndRule, keys langsource/langdest/usedatadir/
exportsubfolder, and `Command=` lines. All rule lines are lowercased by the
parser, which is harmless on Windows paths. Scripts must be UTF-8 with BOM.

The OpenAI API slot is ApiId 7 (aApiBaseName in TESVT_TranslatorApi.pas).
"""

from __future__ import annotations

from pathlib import Path

from . import wire

OPENAI_API_ID = 7
EXPORT_SUBFOLDER = "xtcli_out"  # relative to the loaded file's folder (SaveFile mode 4)


def _rule(
    file: Path | str,
    source: str,
    dest: str,
    *,
    ssts: list[Path] = (),
    sst_params: tuple[int, int] = (0, 1),
    api_notrans: int = 1,
    finalize: bool = False,
    close: str = "closefile",
) -> list[str]:
    p1, p2 = sst_params
    lines = [
        "StartRule",
        f"langsource={source}",
        f"langdest={dest}",
        "usedatadir=0",
    ]
    if finalize:
        lines.append(f"exportsubfolder={EXPORT_SUBFOLDER}")
    lines.append(f"Command=loadfile:{file}")
    for sst in ssts:
        lines.append(f"Command=importsst:{p1}:{p2}:{sst}")
    lines.append(f"Command=apitranslation:{OPENAI_API_ID}:{api_notrans}")
    if finalize:
        lines.append("Command=finalize")
    lines.append(f"Command={close}")
    lines.append("EndRule")
    return lines


def build_script(
    files: list[Path],
    source: str,
    dest: str,
    *,
    ssts: list[Path] = (),
    sst_params: tuple[int, int] = (0, 1),
    finalize: bool = False,
    sentinel_file: Path | None = None,
) -> str:
    lines = ["# generated by xtcli - do not edit", ""]
    for f in files:
        lines += _rule(
            f, source, dest,
            ssts=ssts, sst_params=sst_params, finalize=finalize,
        )
        lines.append("")
    if sentinel_file is not None:
        lines += _rule(
            sentinel_file, source, dest,
            api_notrans=0, close="closeall",
        )
        lines.append("")
    return "\n".join(lines)


def write_sentinel_mcm(directory: Path, source_lang: str = "english") -> Path:
    """Create the sentinel MCM translation file loaded by the final rule.

    Skyrim MCM translation files are UTF-16 LE with BOM, one `$key<TAB>value`
    per line, named `<mod>_<language>.txt`.
    """
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{wire.SENTINEL_KEY}_{source_lang}.txt"
    content = f"${wire.SENTINEL_KEY}\t{wire.SENTINEL_TEXT}\r\n"
    path.write_bytes(b"\xff\xfe" + content.encode("utf-16-le"))
    return path


def write_script(cfg, script: str) -> Path:
    """Place the script where the BatchProcessor dialog auto-loads it."""
    tmp = cfg.batchprocessor_tmp
    tmp.parent.mkdir(parents=True, exist_ok=True)
    tmp.write_text(script, encoding="utf-8-sig", newline="\r\n")
    return tmp
